export function metricName(ui, item) {
  const id = String(item.type_id || ''), fallback = item.display_name || id;
  const exported = /^apple_export\.(HK(?:QuantityTypeIdentifier|CategoryTypeIdentifier)[A-Za-z0-9_]+)\.[0-9a-f]{12}$/.exec(id);
  const key = exported ? exported[1] : id;
  const known = Object.hasOwn(METRIC_LABELS, key) ? METRIC_LABELS[key] : null;
  if (!known) return fallback;
  let name = ui._t(...known);
  if (exported) {
    const split = fallback.indexOf(' · ');
    if (split !== -1) {
      const source = fallback.slice(split + 3).replace(/ · (원본|raw)$/, '');
      if (source) name += ' · ' + source;
    }
    name += ' · ' + ui._t('원본', 'raw');
  }
  return name;
}
export function domainName(ui, domain) {
  return Object.hasOwn(DOMAIN_LABELS, domain) ? ui._t(...DOMAIN_LABELS[domain]) : domain;
}

// Keep searches stable when the UI language changes; identifiers remain searchable.
export function metricSearchText(ui, item) {
  const ko = {_t:(k,e)=>k}, en = {_t:(k,e)=>e};
  return [metricName(ko,item),metricName(en,item),item.display_name,item.type_id,
    domainName(ko,item.domain),domainName(en,item.domain),item.domain].filter(Boolean).join(' ').toLowerCase();
}
